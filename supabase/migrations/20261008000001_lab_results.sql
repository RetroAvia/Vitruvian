-- Vista: risultati con range effettivo e stato
-- -----------------------------------------------------------------------------
create view public.v_lab_results
with (security_invoker = true)
as
select
  r.id,
  r.user_id,
  r.report_id,
  rep.report_date,
  rep.lab_name,
  rep.fasting,
  a.id          as analyte_id,
  a.code,
  a.name,
  a.category,
  a.digits,
  a.sort_order,
  coalesce(r.unit, a.unit) as unit,
  r.value,
  r.value_text,
  r.note,
  -- Range: quello del laboratorio se presente, altrimenti il generico per sesso
  case when r.ref_low  is not null or r.ref_high is not null then r.ref_low
       when p.sex = 'female' then a.ref_low_f else a.ref_low_m end  as ref_low,
  case when r.ref_low  is not null or r.ref_high is not null then r.ref_high
       when p.sex = 'female' then a.ref_high_f else a.ref_high_m end as ref_high,
  (r.ref_low is not null or r.ref_high is not null)                 as ref_from_lab
from public.lab_results r
join public.lab_reports rep on rep.id = r.report_id
join public.lab_analytes a  on a.id = r.analyte_id
left join public.profiles p on p.id = r.user_id;

-- -----------------------------------------------------------------------------
-- RPC: import di uno o più referti (atomico, idempotente per data+laboratorio)
--  Payload:
--  { "reports": [ { "report_date": "2026-04-10", "lab_name": "Synlab", "fasting": true, "notes": null,
--                   "results": [ { "code": "glucose", "name": "Glicemia", "category": "metabolic",
--                                  "value": 88, "value_text": null, "unit": "mg/dL",
--                                  "ref_low": 70, "ref_high": 99, "note": null } ] } ] }
--  Esami con code non presente nel catalogo → creati come esami personali.
-- -----------------------------------------------------------------------------
create or replace function public.import_lab_reports(p jsonb)
returns uuid[]
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_uid      uuid := auth.uid();
  v_reports  jsonb;
  v_rep      jsonb;
  v_res      jsonb;
  v_rep_id   uuid;
  v_an_id    smallint;
  v_code     text;
  v_ids      uuid[] := '{}';
begin
  if v_uid is null then
    raise exception 'Non autenticato' using errcode = '28000';
  end if;

  v_reports := case jsonb_typeof(p)
                 when 'array'  then p
                 when 'object' then coalesce(p -> 'reports', jsonb_build_array(p))
               end;
  if jsonb_typeof(v_reports) is distinct from 'array' or jsonb_array_length(v_reports) = 0 then
    raise exception 'Nessun referto da importare' using errcode = '22023';
  end if;

  for v_rep in select value from jsonb_array_elements(v_reports)
  loop
    if nullif(v_rep ->> 'report_date', '') is null then
      raise exception 'Ogni referto deve avere report_date' using errcode = '22023';
    end if;

    -- Stesso giorno + stesso laboratorio = stesso referto (re-import sicuro)
    select id into v_rep_id
      from public.lab_reports
     where user_id = v_uid
       and report_date = (v_rep ->> 'report_date')::date
       and coalesce(lab_name, '') = coalesce(nullif(trim(v_rep ->> 'lab_name'), ''), '');

    if v_rep_id is null then
      insert into public.lab_reports (user_id, report_date, lab_name, fasting, notes, source, raw_payload)
      values (
        v_uid,
        (v_rep ->> 'report_date')::date,
        nullif(trim(v_rep ->> 'lab_name'), ''),
        (v_rep ->> 'fasting')::boolean,
        nullif(trim(v_rep ->> 'notes'), ''),
        coalesce((p ->> 'source')::public.data_source, 'ai_import'),
        v_rep
      )
      returning id into v_rep_id;
    else
      update public.lab_reports
         set fasting = coalesce((v_rep ->> 'fasting')::boolean, fasting),
             notes   = coalesce(nullif(trim(v_rep ->> 'notes'), ''), notes),
             raw_payload = v_rep
       where id = v_rep_id;
    end if;

    for v_res in select value from jsonb_array_elements(coalesce(v_rep -> 'results', '[]'::jsonb))
    loop
      v_code := lower(regexp_replace(trim(coalesce(v_res ->> 'code', '')), '[^a-zA-Z0-9]+', '_', 'g'));
      v_code := regexp_replace(v_code, '^_+|_+$', '', 'g');
      continue when v_code = '';
      if v_code !~ '^[a-z]' then v_code := 'x_' || v_code; end if;
      continue when nullif(v_res ->> 'value', '') is null and nullif(trim(v_res ->> 'value_text'), '') is null;

      select a.id into v_an_id
        from public.lab_analytes a
       where a.code = v_code and (a.user_id is null or a.user_id = v_uid)
       order by a.user_id nulls last
       limit 1;

      if v_an_id is null then
        insert into public.lab_analytes (user_id, code, name, category, unit, sort_order)
        values (
          v_uid, v_code,
          coalesce(nullif(trim(v_res ->> 'name'), ''), v_code),
          coalesce(
            case when (v_res ->> 'category') in (select unnest(enum_range(null::public.lab_category))::text)
                 then (v_res ->> 'category')::public.lab_category end,
            'other'),
          nullif(trim(v_res ->> 'unit'), ''),
          900
        )
        returning id into v_an_id;
      end if;

      insert into public.lab_results as lr (report_id, user_id, analyte_id, value, value_text, unit, ref_low, ref_high, note)
      values (
        v_rep_id, v_uid, v_an_id,
        (v_res ->> 'value')::numeric,
        nullif(trim(v_res ->> 'value_text'), ''),
        nullif(trim(v_res ->> 'unit'), ''),
        (v_res ->> 'ref_low')::numeric,
        (v_res ->> 'ref_high')::numeric,
        nullif(trim(v_res ->> 'note'), '')
      )
      on conflict (report_id, analyte_id) do update set
        value      = excluded.value,
        value_text = excluded.value_text,
        unit       = excluded.unit,
        ref_low    = excluded.ref_low,
        ref_high   = excluded.ref_high,
        note       = excluded.note;
    end loop;

    v_ids := v_ids || v_rep_id;
  end loop;

  insert into public.ai_imports (user_id, kind, status, payload, target_ids, applied_at)
  values (v_uid, 'lab', 'applied', p, v_ids, now());

  return v_ids;
end;
$$;

revoke execute on function public.import_lab_reports(jsonb) from public, anon;
grant  execute on function public.import_lab_reports(jsonb) to authenticated;

commit;
