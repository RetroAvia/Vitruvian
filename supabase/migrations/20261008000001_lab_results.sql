create table public.lab_reports (
  id           uuid primary key default gen_random_uuid(),
  user_id      uuid not null default auth.uid() references auth.users (id) on delete cascade,
  report_date  date not null,
  lab_name     text,
  fasting      boolean,
  notes        text,
  source       public.data_source not null default 'ai_import',
  raw_payload  jsonb,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  unique (id, user_id)
);

create table public.lab_results (
  id           uuid primary key default gen_random_uuid(),
  report_id    uuid not null,
  user_id      uuid not null default auth.uid(),
  analyte_id   smallint not null references public.lab_analytes (id) on delete restrict,
  value        numeric(12,4),
  value_text   text,                       -- esiti qualitativi ("negativo", "<0,5")
  unit         text,
  ref_low      numeric(12,4),              -- range del laboratorio (ha precedenza)
  ref_high     numeric(12,4),
  note         text,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  foreign key (report_id, user_id) references public.lab_reports (id, user_id) on delete cascade,
  unique (report_id, analyte_id),
  check (value is not null or value_text is not null),
  check (ref_low is null or ref_high is null or ref_low <= ref_high)
);

create index lab_reports_user_date_idx on public.lab_reports (user_id, report_date desc);
create index lab_results_user_analyte_idx on public.lab_results (user_id, analyte_id);
create index lab_results_analyte_idx on public.lab_results (analyte_id);

